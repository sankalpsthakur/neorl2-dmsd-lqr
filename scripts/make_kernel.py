#!/usr/bin/env python3
"""Build a single-file Kaggle kernel script: embeds src/nd/*.py + protocol/sources.sha256 + protocol/data_manifest.json (zlib + base64), injects CFG, appends <kdir>/main.py.
Usage: make_kernel.py <kernel_dir> [--cfg '{"json": ...}']   (kernel_dir holds main.py + kernel-metadata.json; writes script.py and prints its sha256). NOTHING is pushed from here."""
import argparse, base64, hashlib, json, pathlib, zlib
ap = argparse.ArgumentParser(); ap.add_argument("kdir"); ap.add_argument("--cfg", default="{}")
a = ap.parse_args()
root = pathlib.Path(__file__).resolve().parent.parent
kdir = pathlib.Path(a.kdir).resolve()
pkg = {p.name: p.read_text() for p in sorted((root / "src" / "nd").glob("*.py"))}
pkg["sources.sha256"] = (root / "protocol" / "sources.sha256").read_text()
pkg["data_manifest.json"] = (root / "protocol" / "data_manifest.json").read_text()
blob = base64.b64encode(zlib.compress(json.dumps(pkg).encode(), 9)).decode()
header = f'''# AUTO-GENERATED by scripts/make_kernel.py (do not edit); sources: src/nd/*.py + protocol/sources.sha256 + protocol/data_manifest.json + {kdir.name}/main.py
import base64, json, os, sys, zlib
_PKG = json.loads(zlib.decompress(base64.b64decode("{blob}")).decode())
os.makedirs("/tmp/pkg/nd", exist_ok=True)
for _n, _s in _PKG.items():
    open("/tmp/pkg/nd/" + _n, "w").write(_s)
sys.path.insert(0, "/tmp/pkg")
CFG = json.loads({a.cfg!r})
# ---------------------------------------------------------------- main.py
'''
txt = header + (kdir / "main.py").read_text()
(kdir / "script.py").write_text(txt)
print("wrote", kdir / "script.py", len(txt), "bytes sha256", hashlib.sha256(txt.encode()).hexdigest()[:16])
